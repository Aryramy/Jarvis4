/**
 * Runtime Agent Harness Errors (PRE-040A).
 * Strongly typed error classes with controlled error codes for agent governance.
 */

export class RuntimeHarnessError extends Error {
  /**
   * @param {string} message
   * @param {string} [code='RUNTIME_HARNESS_ERROR']
   * @param {Object} [details={}]
   */
  constructor(message, code = 'RUNTIME_HARNESS_ERROR', details = {}) {
    super(message);
    this.name = 'RuntimeHarnessError';
    this.code = code;
    this.details = details;
  }
}

